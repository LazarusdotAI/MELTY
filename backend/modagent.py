async def log(gid, text, kind="info", **extra):
    await db.generations.update_one({"id": gid}, {"$push": {"events": {"t": now(), "type": kind, "text": text, **extra}}})


async def gen_cost(gid):
    agg = await db.ai_calls.aggregate([{"$match": {"generation_id": gid}},
                                       {"$group": {"_id": None, "c": {"$sum": "$cost"}}}]).to_list(1)
    return agg[0]["c"] if agg else 0.0


async def paid_call(gid, pid, messages, tools, max_tokens, purpose):
    if await gen_cost(gid) >= (await get_settings())["generation_ceiling"]:
        raise BudgetExceeded(0.01, 0.0)
    r = await complete(messages, tools, max_tokens, {"project_id": pid, "generation_id": gid, "purpose": purpose})
    await db.generations.update_one({"id": gid}, {"$set": {"provider": r["provider"], "model": r["model"]},
                                                 "$inc": {"cost": r["cost"], "calls": 1}})
    await log(gid, f"{r['label']} ({r['model']}) · {purpose} · {r['input_tokens']}→{r['output_tokens']} tok · ${r['cost']:.4f}", "cost")
    return r


async def create_version(pid, name, kind, gid=None, verification=None):
    p = await db.mods.find_one({"id": pid}, {"_id": 0})
    if not p:
        raise RuntimeError("Mod project was deleted")
    n = await db.versions.count_documents({"project_id": pid})
    vid = new_id()
    await db.versions.insert_one({"id": vid, "project_id": pid, "number": n + 1, "name": name, "kind": kind,
                                  "files": p.get("files", []), "spec_md": p.get("spec_md", ""), "generation_id": gid,
                                  "verification": verification or p.get("verification"),
                                  "build_status": p.get("build_status", "unbuilt"), "created_at": now()})
    await db.mods.update_one({"id": pid}, {"$set": {"current_version_id": vid, "dirty": False, "updated_at": now()}})
    return vid


