def csproj(slug: str, tfm: str) -> str:
    refasm = ('\n  <ItemGroup><PackageReference Include="Microsoft.NETFramework.ReferenceAssemblies" Version="1.0.3" '
              'PrivateAssets="all" /></ItemGroup>') if tfm.startswith("net4") else ""
    return f"""<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>{tfm}</TargetFramework>
    <AssemblyName>{slug}</AssemblyName>
    <RootNamespace>{slug}</RootNamespace>
    <LangVersion>latest</LangVersion>
    <Nullable>disable</Nullable>
    <CopyLocalLockFileAssemblies>false</CopyLocalLockFileAssemblies>
    <GenerateDocumentationFile>false</GenerateDocumentationFile>
    <EnableDefaultCompileItems>true</EnableDefaultCompileItems>
  </PropertyGroup>
  <ItemGroup>
    <Reference Include="$(GameDir)\\BepInEx\\core\\BepInEx.dll" Private="false" />
    <Reference Include="$(GameDir)\\BepInEx\\core\\0Harmony.dll" Private="false" />
    <Reference Include="$(ManagedDir)\\UnityEngine*.dll" Private="false" />
    <Reference Include="$(ManagedDir)\\Assembly-CSharp*.dll" Private="false" />
    <Reference Include="$(ManagedDir)\\Unity.*.dll" Private="false" />
  </ItemGroup>{refasm}
</Project>
"""


def plugin_cs(slug: str, title: str) -> str:
    return f"""using BepInEx;
using BepInEx.Logging;
using HarmonyLib;
using UnityEngine;

namespace {slug}
{{
    [BepInPlugin(PluginGuid, PluginName, PluginVersion)]
    public class Plugin : BaseUnityPlugin
    {{
        public const string PluginGuid = "melty.{slug.lower()}";
        public const string PluginName = "{title.replace('"', '')}";
        public const string PluginVersion = "0.1.0";
        internal static ManualLogSource Log;

        private void Awake()
        {{
            Log = Logger;
            new Harmony(PluginGuid).PatchAll();
            Log.LogInfo("MELTY_READY " + PluginName + " " + PluginVersion);
        }}
    }}
}}
"""


