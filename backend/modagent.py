class WS:
    def __init__(self, gid, files):
        self.gid, self.files = gid, {f["path"]: f["content"] for f in files}

    def as_list(self):
        return [{"path": k, "content": v} for k, v in sorted(self.files.items())]

    async def persist(self):
        await db.generations.update_one({"id": self.gid}, {"$set": {"files": self.as_list()}})


def safe(p, write=False):
    p = (p or "").strip().replace("\\", "/")
    while p.startswith("./"):
        p = p[2:]
    if ".." in p.split("/") or p.startswith("/") or not p:
        raise ValueError(f"invalid path '{p}'")
    if write and (LOCKED.search(p) or not EDITABLE.match(p)):
        raise ValueError(f"'{p}' is locked or not an editable source type (.cs/.md/.json/.txt)")
    return p


async def game_records(mod):
    out = {}
    for role, g in [("host", mod["host"])] + [(f"secondary_{i}", s) for i, s in enumerate(mod.get("secondary", []))]:
        rec = await db.games.find_one({"device_id": mod.get("device_id"), "name": g["name"]}, {"_id": 0}) if mod.get("device_id") else None
        out[role] = {"name": g["name"], "role": g.get("role", "host"), "detected": rec}
    return out


async def dispatch(mod, gid, op, params, timeout, label):
    d = await online_device(mod.get("device_id"))
    if not d:
        return None, "Companion offline — cannot run on the user's PC. Finish honestly (code unbuilt/untested)."
    j = await enqueue(d["id"], op, params, mod["id"], gid, label)
    if j["status"] == "needs_approval":
        await log(gid, f"Waiting for your approval of '{op}' on {d['hostname']}…", "warn")
    j = await wait_job(j["id"], timeout)
    return j, None


async def run_tool(name, args, ws, mod, state):
    gid = ws.gid
    try:
        if name == "list_files":
            return json.dumps([{"path": k, "bytes": len(v), "locked": bool(LOCKED.search(k))} for k, v in ws.files.items()])
        if name == "read_file":
            p = safe(args.get("path"))
            return ws.files.get(p, f"ERROR: {p} not found")
        if name == "write_file":
            if "content" not in args:
                return "ERROR: missing content (output truncated?) — split into smaller files"
            p = safe(args.get("path"), True)
            ws.files[p] = args["content"]
            await ws.persist()
            await log(gid, f"Wrote {p} ({args['content'].count(chr(10)) + 1} lines)", "file")
            return f"OK wrote {p}"
        if name == "replace_in_file":
            p = safe(args.get("path"), True)
            src = ws.files.get(p)
            if src is None:
                return f"ERROR: {p} not found"
            n = src.count(args.get("old") or "\0")
            if n != 1:
                return f"ERROR: snippet found {n} times; must match exactly once"
            ws.files[p] = src.replace(args["old"], args.get("new", ""))
            await ws.persist()
            await log(gid, f"Edited {p}", "file")
            return f"OK edited {p}"
        if name == "delete_file":
            p = safe(args.get("path"), True)
            ws.files.pop(p, None)
            await ws.persist()
            return f"OK deleted {p}"
        if name == "get_adapter_docs":
            return (await adapters.docs_for([mod["host"]["name"]] + [s["name"] for s in mod.get("secondary", [])]))[:12000]
        if name == "get_game_info":
            return json.dumps(await game_records(mod), default=str)[:12000]
        if name == "build":
            if state["builds"] >= MAX_BUILDS:
                return "ERROR: build budget exhausted; finish and report remaining errors."
            tc = mod.get("toolchain") or "bepinex5-csharp"
            syntax, note = lua_syntax_errors(ws.as_list(), tc)
            if syntax:
                await log(gid, f"Build stopped: {len(syntax)} Lua syntax error(s) found before sending it to your PC", "test_fail")
                return json.dumps({"ok": False, "status": "syntax_error", "error": f"Lua syntax errors ({engine_name(tc)}, the game's own Lua)",
                                   "errors": syntax[:40], "warnings": 0, "log_tail": ""})
            if note:
                await log(gid, note, "warn")
            state["builds"] += 1
            await log(gid, f"Build #{state['builds']} dispatched to companion…", "test")
            j, err = await dispatch(mod, gid, "build_mod", build_params(mod, ws), 420, f"Build {mod['title']}")
            if err:
                await log(gid, err, "warn")
                return err
            r = j.get("result") or {}
            state["last_build"] = j
            state["build_hash"] = files_hash(ws.as_list())
            ok = j["status"] == "done" and r.get("ok")
            why = r.get("error") or f"{len(r.get('errors', []))} compiler errors"
            await log(gid, "Build succeeded" if ok else f"Build failed: {why}",
                      "test_pass" if ok else "test_fail", job_id=j["id"])
            return json.dumps({"ok": ok, "status": j["status"], "timed_out": j.get("timed_out", False), "error": r.get("error"),
                               "errors": r.get("errors", [])[:40], "warnings": len(r.get("warnings", [])),
                               "log_tail": (j.get("log") or "")[-2500:]})
        if name == "test_in_game":
            b = state.get("last_build")
            if not b or not (b.get("result") or {}).get("ok"):
                return "ERROR: build successfully first."
            if state.get("build_hash") != files_hash(ws.as_list()):
                return "ERROR: files changed since the last successful build; build again before testing."
            if state["tests"] >= MAX_TESTS:
                return "ERROR: test budget exhausted; finish."
            state["tests"] += 1
            secs = max(20, min(120, int(args.get("seconds") or 45)))
            await log(gid, f"In-game test #{state['tests']}: install dev build → launch → observe {secs}s → restore…", "test")
            params = test_params(mod, b, secs)
            j, err = await dispatch(mod, gid, "test_mod", params, secs + 300, f"Test {mod['title']}")
            if err:
                return err
            r = j.get("result") or {}
            v = verdict(j)
            state["verification"] = v
            state["verification_hash"] = state.get("build_hash")
            await log(gid, describe(v), "test_pass" if v["passed"] else "test_fail", job_id=j["id"], verification=v)
            shot = next((a for a in j.get("artifacts", []) if a["name"] == "screenshot.png"), None)
            if shot:
                state["pending_image"] = (await asyncio.to_thread(shrink, shot["storage_path"]), state["tests"], j["id"])
                await log(gid, f"Screenshot from test #{state['tests']} sent for visual review", "visual", job_id=j["id"])
            else:
                await log(gid, "No screenshot captured on this test — visual review skipped", "warn")
            return json.dumps({**v, "screenshot": "attached in next message" if shot else "none captured",
                               "log_tail": r.get("bepinex_log_tail", "")[-4000:]})
        if name == "add_knowledge_note":
            host_rec = (await game_records(mod))["host"]["detected"] or {}
            await adapters.add_note(args["game"], args["note"], host_rec.get("game_version", ""), "ai", mod["id"])
            await log(gid, f"Knowledge note saved for {args['game']}", "info")
            return "OK"
        if name in workshop.NAMES:
            return await workshop.agent_tool(name, args, mod, gid, log)
        return f"ERROR: unknown tool {name}"
    except ValueError as e:
        return f"ERROR: {e}"


def shrink(storage_path: str) -> str:
    data, _ = get_object(storage_path)
    im = Image.open(io.BytesIO(data)).convert("RGB")
    im.thumbnail((1024, 576))  # image tokens grow with pixels; 1024 wide still shows missing textures, UI overlap and error dialogs
    out = io.BytesIO()
    im.save(out, "JPEG", quality=70)
    return "data:image/jpeg;base64," + base64.b64encode(out.getvalue()).decode()


def tc_params(mod):
    a = mod.get("_adapter") or {}
    return {"toolchain": mod.get("toolchain") or "bepinex5-csharp", "docs": a.get("docs_name"), "game_folder": a.get("game_folder"),
            "map": a.get("default_map"), "mutator_class": mod["slug"], "loader_url": (a.get("loader") or {}).get("url")}


def files_hash(files):
    return hashlib.sha256(json.dumps(sorted((f["path"], f["content"]) for f in files)).encode()).hexdigest()


def build_params(mod, ws):
    return {"project_id": mod["id"], "slug": mod["slug"], "files": ws.as_list(), "host_name": mod["host"]["name"], **tc_params(mod)}


def artifact_of(job):
    return next((a for a in job.get("artifacts", []) if a["name"].endswith((".dll", ".u", ".zip"))), None)


def test_params(mod, build_job, secs):
    return {"slug": mod["slug"], "host_name": mod["host"]["name"], "seconds": secs,
            "dll": artifact_of(build_job), "plugin_guid": f"melty.{mod['slug'].lower()}",
            "secondary": [s["name"] for s in mod.get("secondary", [])], **tc_params(mod)}


def verdict(job):
    r = job.get("result") or {}
    checks = r.get("checks", [])
    c = {"installed": bool(r.get("installed")), "launched": bool(r.get("launched")),
         "plugin_loaded": bool(r.get("plugin_loaded")), "no_plugin_errors": not r.get("plugin_errors"),
         "melty_checks": bool(checks) and all(x.get("pass") for x in checks), "restored": bool(r.get("restored"))}
    return {"passed": job["status"] == "done" and all(c.values()), "checks": c, "melty_checks": checks,
            "plugin_errors": (r.get("plugin_errors") or [])[:10], "game_version": r.get("game_version"),
            "alive_at_end": r.get("alive_at_end"), "job_id": job["id"], "at": now(),
            "manual_needed": ["Gameplay feel & balance", "Saving and loading", "Multiplayer joining", "Multiplayer sync"]}


def describe(v):
    c = v["checks"]
    if not c["launched"]:
        return "The game didn't start for the test."
    if not c["plugin_loaded"]:
        return "The game started, but the mod didn't load."
    if not c["no_plugin_errors"]:
        return "The mod loaded, but the game reported errors in it."
    return "The mod loaded in the game without errors."


def feature_results(names, checks):
    got = {}
    for x in checks or []:
        got[x["name"]] = x
    return [{"name": n, "seen": n in got, "pass": bool(got.get(n, {}).get("pass")), "detail": (got.get(n) or {}).get("detail", "")} for n in names]


def confirmed(names, checks):
    return bool(names) and all(r["pass"] for r in feature_results(names, checks))


