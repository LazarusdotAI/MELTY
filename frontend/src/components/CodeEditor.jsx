import { useState } from "react";
import { FileCode, Lock, Save } from "lucide-react";
import { toast } from "sonner";
import { api, errMsg } from "../lib/api";
import { Button } from "./ui/button";

export default function CodeEditor({ mod, onSaved, readOnly }) {
  const files = mod.files || [];
  const [sel, setSel] = useState(files.find((f) => f.path === "Plugin.cs")?.path || files[0]?.path);
  const [drafts, setDrafts] = useState({});
  const cur = files.find((f) => f.path === sel);
  const locked = /\.(csproj|props|targets)$/.test(sel || "");
  const val = drafts[sel] ?? cur?.content ?? "";
  const dirty = drafts[sel] !== undefined && drafts[sel] !== cur?.content;
  const save = async () => {
    try {
      await api.put(`/mods/${mod.id}/files`, { path: sel, content: val });
      setDrafts({ ...drafts, [sel]: undefined });
      toast.success(`Saved ${sel}. Rebuild before releasing.`);
      onSaved();
    } catch (e) {
      toast.error(errMsg(e));
    }
  };
  return (
    <div className="flex h-full min-h-0" data-testid="code-editor">
      <div className="w-52 border-r border-slate-800 overflow-auto scroll-thin py-2" data-testid="file-explorer">
        {files.map((f) => (
          <button key={f.path} data-testid={`file-${f.path}`} onClick={() => setSel(f.path)}
            className={`w-full text-left px-3 py-1.5 text-xs font-mono flex items-center gap-2 ${sel === f.path ? "bg-cyan-500/10 text-cyan-300" : "text-slate-400 hover:text-slate-100"}`}>
            {/\.csproj$/.test(f.path) ? <Lock className="w-3 h-3" /> : <FileCode className="w-3 h-3" />}<span className="truncate">{f.path}</span>
          </button>
        ))}
      </div>
      <div className="flex-1 flex flex-col min-w-0">
        <div className="flex items-center gap-2 px-3 py-2 border-b border-slate-800 text-xs">
          <span className="font-mono text-slate-300">{sel}</span>
          {locked && <span className="text-amber-300 flex items-center gap-1"><Lock className="w-3 h-3" /> generated by the platform</span>}
          <Button data-testid="save-file-button" size="sm" disabled={!dirty || locked || readOnly} onClick={save} className="ml-auto h-7 bg-cyan-500 hover:bg-cyan-400 text-[#08090d]"><Save className="w-3 h-3 mr-1" /> Save</Button>
        </div>
        <textarea data-testid="code-textarea" spellCheck={false} value={val} readOnly={locked || readOnly}
          onChange={(e) => setDrafts({ ...drafts, [sel]: e.target.value })}
          className="flex-1 w-full bg-[#0a0b0e] text-cyan-100 font-mono text-[12.5px] leading-relaxed p-4 outline-none resize-none scroll-thin" />
      </div>
    </div>
  );
}
